import { mkdir, readFile, writeFile } from 'node:fs/promises';

const [client, styles] = await Promise.all([
  readFile(new URL('../src/client.js', import.meta.url), 'utf8'),
  readFile(new URL('../src/skins.css', import.meta.url), 'utf8'),
]);

const library = new URL('../lib/', import.meta.url);
await mkdir(library, { recursive: true });
await writeFile(new URL('client.js', library), `// Generated by npm run build.
window.__ModuleLoader__.load({
  id: 'dsh-glass-skins',
  factory: (require) => {
    const styles = ${JSON.stringify(styles)};
${client.split('\n').map((line) => line ? '    ' + line : '').join('\n')}
    return { name: 'dsh-glass-skins', inject: ['slots', 'locale'], apply };
  },
});
`);
